#!/usr/bin/env node
/**
 * Regenerate `lib/reference-data.js` from pi-ai's provider data (MIT): one
 * entry per model, keyed by {@link modelKey}, taken from the model's own
 * vendor where it ships it (Anthropic's for Claude, Moonshot's for Kimi …),
 * else from the first aggregator that lists it.
 *
 *   npm pack @earendil-works/pi-ai && tar -xzf earendil-works-pi-ai-*.tgz
 *   node scripts/gen-reference.mjs --pi package/dist/providers/data
 *
 * The data is read as JSON; no code of the package runs.
 */
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { modelKey } from "../lib/reference.js";

const args = process.argv.slice(2);
const dir = args[args.indexOf("--pi") + 1];
if (!args.includes("--pi") || !dir) {
  console.error("usage: node scripts/gen-reference.mjs --pi <pi-ai package/dist/providers/data>");
  process.exit(2);
}
const version = (() => {
  try {
    return JSON.parse(readFileSync(join(dir, "..", "..", "..", "package.json"), "utf8")).version;
  } catch {
    return "unknown";
  }
})();

/** Vendors first (their own data on their own models), then aggregators. */
const PREFERRED = [
  "anthropic", "openai", "google", "xai", "deepseek", "moonshotai", "zai", "minimax", "xiaomi", "mistral", "meta", "nvidia",
  "qwen-token-plan", "qwen-token-plan-individual", "kimi-coding", "ant-ling", "cerebras", "groq", "fireworks", "together", "huggingface", "baseten",
  "openrouter", "vercel-ai-gateway", "opencode", "opencode-go", "cloudflare-workers-ai", "cloudflare-ai-gateway", "github-copilot", "amazon-bedrock", "google-vertex",
];
const rank = (provider) => {
  const index = PREFERRED.indexOf(provider);
  return index < 0 ? PREFERRED.length : index;
};
const SKIP = /realtime|audio|-image|image-|tts|embedding|moderation|transcribe|whisper|dall-e|sora|veo|imagen|lyria/i;

/** The reasoning levels a model offers (pi-ai's rule: null = unsupported; xhigh / max only when named). */
function reasoningOf(model) {
  if (!model.reasoning) return null;
  const map = model.thinkingLevelMap ?? {};
  const levels = ["minimal", "low", "medium", "high"].filter((level) => map[level] !== null);
  for (const level of ["xhigh", "max"]) if (typeof map[level] === "string") levels.push(level);
  return { levels, off: map.off !== null };
}

function flagsOf(model) {
  const compat = model.compat ?? {};
  const flags = {};
  if (compat.forceAdaptiveThinking || compat.supportsMidConvoEffort) flags.adaptive = true;
  if (compat.supportsTemperature === false) flags.noTemperature = true;
  if (compat.maxTokensField && compat.maxTokensField !== "max_tokens") flags.maxTokensField = compat.maxTokensField;
  if (compat.requiresReasoningContentOnAssistantMessages) flags.reasoningOnAssistant = true;
  return flags;
}

const best = new Map();
const files = readdirSync(dir).filter((name) => name.endsWith(".json")).sort();
for (const file of files) {
  const provider = file.replace(/\.json$/, "");
  const data = JSON.parse(readFileSync(join(dir, file), "utf8"));
  for (const group of Object.values(data)) {
    for (const model of Object.values(group ?? {})) {
      if (!model?.id || (model.type && model.type !== "chat") || SKIP.test(model.id)) continue;
      const key = modelKey(model.id);
      const current = best.get(key);
      if (current && current.rank <= rank(provider)) continue;
      const flags = flagsOf(model);
      best.set(key, {
        rank: rank(provider),
        entry: {
          name: String(model.name ?? model.id).replace(/^[^:]{2,30}:\s+/, "").replace(/\s*\(free\)$/i, ""),
          ...(model.contextWindow ? { context: model.contextWindow } : {}),
          ...(model.maxTokens ? { output: model.maxTokens } : {}),
          ...(Array.isArray(model.input) && model.input.includes("image") ? { image: true } : {}),
          ...(reasoningOf(model) ? { reasoning: reasoningOf(model) } : {}),
          ...(Object.keys(flags).length ? { flags } : {}),
          from: provider,
        },
      });
    }
  }
}

const keys = [...best.keys()].sort();
const header = `/**
 * Model reference: generated by scripts/gen-reference.mjs from pi-ai ${version}'s
 * provider data (MIT, https://github.com/earendil-works/pi). Do not edit by hand.
 *
 * Keyed by \`modelKey(id)\` (reference.js): \`name\`, \`context\`, \`output\`,
 * \`image\`, \`reasoning\` ({ levels, off }), \`flags\` (adaptive thinking, no
 * temperature, the output-cap field, reasoning content sent back), \`from\`
 * (the pi-ai catalog it came from). No prices: a site's prices are its own.
 *
 * @module dsh-custom-models/reference-data
 */
`;
const body = keys.map((key) => `  ${JSON.stringify(key)}: ${JSON.stringify(best.get(key).entry)},`).join("\n");
writeFileSync(new URL("../lib/reference-data.js", import.meta.url), `${header}export const REFERENCE = Object.freeze({\n${body}\n});\n`);
console.log(`wrote lib/reference-data.js: ${keys.length} models from ${files.length} catalogs`);
